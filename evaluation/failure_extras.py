"""
failure_extras.py - step 9 additions picked by the team leader (Sat 14 Nov 21:20), test people:

  A. Uncertainty ranges. Our test set has 72 people; with different people the numbers would
     come out a bit different. A "bootstrap" estimates by how much: draw 72 people at random
     FROM our 72, with repeats allowed (some twice, some not at all), recompute the score, do
     this 1000 times, and report the range that holds the middle 95% of the results. People
     are drawn, not windows, because one person's windows are alike; drawing windows would
     pretend we had far more independent evidence than we do.
  B. Failures per person: are the misses and false alarms spread over many people, or do a few
     people cause most of them?
  C. The corrector on REAL marked tremor where it does worse than no filter: the 2 worst
     sequences, charted (find_failures.py's corrector examples were unmarked shaking).
  D. The demo page's weak spot: a hand held still, where One Euro beats our model. Charted
     through the server's own code with the demo page's replayed tremor (test people).

Models: detector v2 with its cut-off and corrector v4 (penalty 2), as in the app.
Run from the repository folder (about a minute):
    python evaluation/failure_extras.py
Writes evaluation/results/failures/extras.md and four charts next to it.
"""

import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from evaluation.evaluate_corrector import SKIP, corrector_offsets, detector_gate  # noqa: E402
from evaluation.find_failures import CORRECTOR_FILE, DETECTOR_FILE, THRESHOLD_FILE  # noqa: E402
from evaluation.metrics import band_power  # noqa: E402
from models.corrector.live import load_corrector  # noqa: E402
from models.detector.features import compute_features  # noqa: E402
from models.detector.predict import Detector  # noqa: E402

DERIVED = ROOT / "data" / "derived"
OUT = ROOT / "evaluation" / "results" / "failures"
RATE = 100
DRAWS = 1000
SEED = 0


def units(subjects):
    """Bootstrap units: one per person. Windows with no person (synthetic movement only) are
    each their own unit, since they come from independent random paths."""
    subjects = np.array(subjects, dtype=object)
    synthetic = subjects == "synthetic"
    subjects[synthetic] = ["synthetic_%d" % i for i in range(synthetic.sum())]
    names, index = np.unique(subjects.astype(str), return_inverse=True)
    return names, index


def bootstrap(per_unit_numerators, per_unit_denominators, rng):
    """95% range of sum(numerator) / sum(denominator) when the units are redrawn with repeats."""
    n = len(per_unit_numerators)
    values = []
    for _ in range(DRAWS):
        pick = rng.integers(0, n, n)
        values.append(per_unit_numerators[pick].sum() / per_unit_denominators[pick].sum())
    return np.percentile(values, [2.5, 97.5])


def main():
    rng = np.random.default_rng(SEED)
    lines = ["# Step 9 additions: uncertainty, failures per person, more failure cases",
             "", "Generated by `python evaluation/failure_extras.py` (test people; detector v2 with its "
             "cut-off, corrector v4 with penalty 2, as in the app).", ""]

    # ------------------------------------------------ detector: scores per window
    detector = Detector(DETECTOR_FILE, THRESHOLD_FILE)
    test = np.load(DERIVED / "detector_test.npz")
    scores = detector.classifier.predict_proba(compute_features(test["xy"]))[:, 1]
    labels = test["label"].astype(bool)
    pred = scores >= detector.threshold
    names, unit = units(test["subject"])
    n_units = len(names)
    tremor_w = np.bincount(unit, labels, n_units)
    missed_w = np.bincount(unit, labels & ~pred, n_units)
    clear_w = np.bincount(unit, ~labels, n_units)
    alarm_w = np.bincount(unit, ~labels & pred, n_units)
    m_lo, m_hi = bootstrap(missed_w, tremor_w, rng)
    f_lo, f_hi = bootstrap(alarm_w, clear_w, rng)
    people = np.array([not n.startswith("synthetic_") for n in names])

    # ------------------------------------------------ corrector: per sequence
    data = np.load(DERIVED / "corrector_test.npz")
    shaky, clean, marked = data["shaky"], data["clean"], data["tremor"].astype(bool)
    gate = detector_gate(detector, shaky)[..., None]
    ours = shaky + gate * corrector_offsets(load_corrector(CORRECTOR_FILE), shaky)
    dist = lambda out: np.linalg.norm(out[:, SKIP:] - clean[:, SKIP:], axis=2).mean(axis=1)
    d_ours, d_none = dist(ours), dist(shaky)
    cnames, cunit = units(data["subject"][marked])
    nc = len(cnames)
    ours_u = np.bincount(cunit, d_ours[marked], nc)
    none_u = np.bincount(cunit, d_none[marked], nc)
    seqs_u = np.bincount(cunit, None, nc).astype(float)
    shake_before = np.array([band_power((shaky[i:i + 1] - clean[i:i + 1])[:, SKIP:]) for i in np.flatnonzero(marked)])
    shake_after = np.array([band_power((ours[i:i + 1] - clean[i:i + 1])[:, SKIP:]) for i in np.flatnonzero(marked)])
    left_u = np.bincount(cunit, shake_after, nc)
    before_u = np.bincount(cunit, shake_before, nc)
    o_lo, o_hi = bootstrap(ours_u, seqs_u, rng)
    n_lo, n_hi = bootstrap(none_u, seqs_u, rng)
    r_lo, r_hi = bootstrap(left_u, before_u, rng)       # share of shake LEFT over

    lines += ["## A. How sure are the main numbers? (95%% ranges, people redrawn %d times)" % DRAWS, "",
              "| Number | Our test result | 95% range |", "|---|---|---|",
              "| Detector: missed tremor windows | %.1f%% | %.1f%% to %.1f%% |" % (
                  100 * missed_w.sum() / tremor_w.sum(), 100 * m_lo, 100 * m_hi),
              "| Detector: false alarms | %.1f%% | %.1f%% to %.1f%% |" % (
                  100 * alarm_w.sum() / clear_w.sum(), 100 * f_lo, 100 * f_hi),
              "| Corrector, marked tremor: distance from the path, ours (px) | %.2f | %.2f to %.2f |" % (
                  d_ours[marked].mean(), o_lo, o_hi),
              "| Corrector, marked tremor: distance from the path, no filter (px) | %.2f | %.2f to %.2f |" % (
                  d_none[marked].mean(), n_lo, n_hi),
              "| Corrector, marked tremor: tremor removed | %.0f%% | %.0f%% to %.0f%% |" % (
                  100 * (1 - shake_after.sum() / shake_before.sum()), 100 * (1 - r_hi), 100 * (1 - r_lo)),
              "", "Units redrawn: %d test people with detector windows (plus %d windows of synthetic "
              "movement only, each its own unit); %d people with marked-tremor corrector sequences. "
              "Distances here are over the whole sequence after 2.56 s (moving and still together)." % (
                  people.sum(), (~people).sum(), nc), ""]

    # ------------------------------------------------ B. failures per person
    lines += ["## B. Failures per person (detector)", ""]
    for what, fails, total in [("missed tremor windows", missed_w, tremor_w), ("false alarms", alarm_w, clear_w)]:
        sel = people & (total > 0)
        f, t = fails[sel], total[sel]
        order = np.argsort(-f)
        top5 = f[order[:5]].sum() / f.sum()
        cumulative = np.cumsum(f[order]) / f.sum()
        half = int(np.searchsorted(cumulative, 0.5) + 1)
        lines.append("- **%s** (people only, %d people with such windows, %d failures): %d people "
                     "have none; the 5 people with the most cause %.0f%% of them; %d people cause "
                     "half. Worst person: %d of %d windows." % (
                         what, sel.sum(), f.sum(), (f == 0).sum(), 100 * top5, half,
                         f[order[0]], t[order[0]]))
    lines += ["", "Chart: `failures_per_person.png`.", ""]

    fig, axes = plt.subplots(1, 2, figsize=(13, 4))
    for ax, (title, fails, total) in zip(axes, [("Missed tremor windows", missed_w, tremor_w),
                                                ("False alarms", alarm_w, clear_w)]):
        sel = people & (total > 0)
        share = fails[sel] / total[sel]
        order = np.argsort(-fails[sel])
        ax.bar(np.arange(sel.sum()), fails[sel][order], color="#d9661a")
        ax.set(title="%s per test person (most first)" % title, xlabel="test person", ylabel="windows")
        ax2 = ax.twinx()
        ax2.plot(np.arange(sel.sum()), share[order], "k.", markersize=4)
        ax2.set(ylabel="share of that person's windows", ylim=(0, 1.05))
    fig.tight_layout()
    fig.savefig(OUT / "failures_per_person.png", dpi=80)
    plt.close(fig)

    # ------------------------------------------------ C. corrector worse on real marked tremor
    worse = (d_ours - d_none)
    candidates = np.flatnonzero(marked & (worse > 0))
    lines += ["## C. Corrector worse than no filter on REAL marked tremor", "",
              "%d of %d test sequences with marked tremor end up further from the intended path "
              "with our system than with no filter at all." % (len(candidates), marked.sum()), ""]
    for k, i in enumerate(candidates[np.argsort(-worse[candidates])][:2], start=1):
        t = np.arange(SKIP, shaky.shape[1]) / RATE
        fig, axes = plt.subplots(1, 2, figsize=(14, 4.5))
        for name, out, style in [("intended", clean, "k-"), ("raw (shaky)", shaky, "r:"), ("our system", ours, "b-")]:
            axes[0].plot(out[i, SKIP:, 0], out[i, SKIP:, 1], style, label=name, linewidth=1)
            axes[1].plot(t, np.linalg.norm(out[i, SKIP:] - clean[i, SKIP:], axis=1), style, label=name)
        axes[0].invert_yaxis()
        axes[0].set(title="Path on screen (px)")
        axes[0].legend(fontsize=8)
        axes[1].plot(t, 30 * gate[i, SKIP:, 0], color="orange", label="detector gate (x30)")
        axes[1].set(title="Distance from the intended path (px)", xlabel="time (s)")
        axes[1].legend(fontsize=8)
        fig.suptitle("Marked tremor, corrector worse: %s, %s, size %.1f px, %.1f Hz" % (
            data["condition"][i], data["task_type"][i], data["strength_px"][i], data["peak_hz"][i]), fontsize=10)
        fig.tight_layout()
        fig.savefig(OUT / ("corrector_worse_tremor_%d.png" % k), dpi=80)
        plt.close(fig)
        lines.append("- `corrector_worse_tremor_%d.png`: ours %.2f px, no filter %.2f px; %s, %s, tremor "
                     "%.1f px at %.1f Hz; mean gate %.2f" % (
                         k, d_ours[i], d_none[i], data["condition"][i], data["task_type"][i],
                         data["strength_px"][i], data["peak_hz"][i], gate[i, SKIP:].mean()))
    by_size = []
    for name, lo, hi in [("mild (under 3 px)", 0, 3), ("medium (3-10 px)", 3, 10), ("strong (over 10 px)", 10, 1e9)]:
        m = marked & (data["strength_px"] >= lo) & (data["strength_px"] < hi)
        by_size.append("%s %d of %d" % (name, (m & (worse > 0)).sum(), m.sum()))
    lines += ["", "Worse than no filter, by tremor size: " + "; ".join(by_size) + ".", ""]

    # ------------------------------------------------ D. the still hand on the demo page
    import evaluation.compare_modes as cm
    import server.main as server
    server.DEMO_TREMOR_FILE = cm.DEMO_FILES["test"]
    t, paths = cm.intended_paths()
    runs = {mode: cm.run(mode, t, paths["still"], level="medium") for mode in ("none", "one_euro", "learned")}
    keep = t >= cm.WARMUP
    offs = {mode: np.linalg.norm(out - paths["still"], axis=1) for mode, (out, _) in runs.items()}
    fig, ax = plt.subplots(figsize=(13, 4))
    window = (t >= 3) & (t <= 13)
    for mode, colour, label in [("none", "#999999", "no filter"), ("one_euro", "#2e7d5b", "One Euro"),
                                ("learned", "#3b2314", "our model")]:
        ax.plot(t[window], offs[mode][window], color=colour, label=label, linewidth=1)
    ax.plot(t[window], 10 * runs["learned"][1][window], color="#d9661a", linestyle="--", label="our gate (x10)")
    ax.set(title="Hand held still with replayed medium tremor (demo page code): distance from the hold point",
           xlabel="time (s)", ylabel="px")
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(OUT / "demo_still_hand.png", dpi=80)
    plt.close(fig)
    lines += ["## D. The demo page's weak spot: a hand held perfectly still", "",
              "Medium replayed tremor of test people, hand still, after a 3 s warm-up (server code, as "
              "`compare_modes.py`): average distance from the hold point: no filter %.2f px, One Euro "
              "%.2f px, our model %.2f px; our correction was more than half on for %.0f%% of the "
              "time. Chart: `demo_still_hand.png` (seconds 3-13)." % (
                  offs["none"][keep].mean(), offs["one_euro"][keep].mean(), offs["learned"][keep].mean(),
                  100 * np.nanmean(runs["learned"][1][keep] > 0.5)), "",
              "This project is a prototype and is not medical advice.", ""]
    (OUT / "extras.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
