"""
find_failures.py - where do our models go wrong? (test people only)

Saves to evaluation/results/failures/:
  - detector_missed_1..3.png    : the 3 most confident MISSED cases (tremor called "no tremor")
  - detector_false_alarm_1..3.png: the 3 most confident FALSE ALARMS
  - corrector_worse_1..2.png    : 2 sequences where our system does worse than no filter or One Euro
  - failure_facts.md            : the facts about each example, and counts of which kinds of
                                  windows fail most often (the patterns)
The explanations are written by hand in failures.md, after looking at these charts.

It analyses the models the app uses (detector v2 with its cut-off, corrector v5_k3), named
explicitly so it never silently switches models.

Run from the repository folder (about a minute):
    python evaluation/find_failures.py
"""

import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from scipy.signal import periodogram

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from baselines.classical_filters import OneEuroFilter  # noqa: E402
from evaluation.evaluate_corrector import SKIP, corrector_offsets, detector_gate  # noqa: E402
from evaluation.metrics import run_filter  # noqa: E402
from models.corrector.live import load_corrector  # noqa: E402
from models.detector.features import compute_features  # noqa: E402
from models.detector.predict import Detector  # noqa: E402

DETECTOR_FILE = ROOT / "models" / "detector" / "detector_v2.joblib"
THRESHOLD_FILE = ROOT / "models" / "detector" / "detector_v2_threshold.json"
CORRECTOR_FILE = ROOT / "models" / "corrector" / "weights_v5_k3.pt"

DERIVED = ROOT / "data" / "derived"
OUT = ROOT / "evaluation" / "results" / "failures"
RATE = 100


def pick_diverse(order, subjects, n=3):
    """Take the first n examples from `order`, at most one per person (for variety)."""
    chosen, seen = [], set()
    for i in order:
        if subjects[i] not in seen or subjects[i] == "synthetic":
            chosen.append(i)
            seen.add(subjects[i])
        if len(chosen) == n:
            break
    return chosen


def facts(test, i, score):
    return ("score %.3f; source: %s; diagnosis: %s; task: %s; tremor size %.1f px; "
            "hand %s; look-alike movement in %.0f%% of the window; subject %s" % (
                score, test["source"][i], test["condition"][i], test["task_type"][i],
                test["strength_px"][i], "moving" if test["moving"][i] else "still",
                100 * test["lookalike_share"][i], test["subject"][i]))


def plot_window(test, i, score, title, path):
    xy, tremor = test["xy"][i], test["tremor_xy"][i]
    t = np.arange(len(xy)) / RATE
    fig, axes = plt.subplots(1, 3, figsize=(15, 4))
    axes[0].plot(xy[:, 0] - xy[0, 0], label="x")
    axes[0].plot(xy[:, 1] - xy[0, 1], label="y")
    axes[0].set(title="Cursor position (px, from start)", xlabel="sample (10 ms)")
    axes[0].legend()
    axes[1].plot(t, tremor[:, 0], label="tremor x")
    axes[1].plot(t, tremor[:, 1], label="tremor y")
    axes[1].set(title="Tremor part that was added (px)", xlabel="time (s)")
    axes[1].legend()
    freqs, power = periodogram(np.diff(xy, axis=0), fs=RATE, axis=0, detrend="constant")
    axes[2].semilogy(freqs[1:], power.sum(axis=1)[1:])
    axes[2].axvspan(3, 12, color="orange", alpha=0.2)
    axes[2].set(title="Spectrum of the movement (3-12 Hz shaded)", xlabel="frequency (Hz)")
    fig.suptitle("%s - score %.3f - %s, %s, %s, size %.1f px" % (
        title, score, test["source"][i], test["condition"][i], test["task_type"][i],
        test["strength_px"][i]), fontsize=10)
    fig.tight_layout()
    fig.savefig(path, dpi=80)
    plt.close(fig)


def share_table(title, column, values, mask_fail, mask_all, test):
    rows = ["### %s" % title, "", "| Group | Windows | Of which failed | Failure rate |", "|---|---|---|---|"]
    for v in values:
        g = mask_all & (test[column] == v)
        if g.sum():
            rows.append("| %s | %d | %d | %.1f%% |" % (v, g.sum(), (g & mask_fail).sum(),
                                                       100 * (g & mask_fail).sum() / g.sum()))
    return rows + [""]


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    lines = ["# Failure facts (generated by `python evaluation/find_failures.py`)", "",
             "Models: detector v2 (cut-off from `detector_v2_threshold.json`) and corrector v5 (shake penalty 3), gated "
             "by detector v2, as in the app. Test people only.", ""]

    # ---------------- detector
    detector = Detector(DETECTOR_FILE, THRESHOLD_FILE)
    test = dict(np.load(DERIVED / "detector_test.npz"))
    scores = detector.classifier.predict_proba(compute_features(test["xy"]))[:, 1]
    labels = test["label"].astype(bool)
    pred = scores >= detector.threshold
    missed, alarms = labels & ~pred, ~labels & pred
    print("Detector on test: %d missed, %d false alarms" % (missed.sum(), alarms.sum()))

    lines += ["## Detector examples (cut-off %.3f)" % detector.threshold, ""]
    for name, mask, order in [("missed", missed, np.argsort(scores)),
                              ("false_alarm", alarms, np.argsort(-scores))]:
        chosen = pick_diverse([i for i in order if mask[i]], test["subject"])
        for k, i in enumerate(chosen, start=1):
            file = "detector_%s_%d.png" % (name, k)
            plot_window(test, i, scores[i], name.replace("_", " ").upper(), OUT / file)
            lines.append("- `%s`: %s" % (file, facts(test, i, scores[i])))
        lines.append("")

    # Patterns: which kinds of windows fail most often.
    lines += ["## Patterns among missed cases (tremor windows only)", ""]
    sizes = np.where(test["strength_px"] < 3, "mild", np.where(test["strength_px"] < 10, "medium", "strong"))
    test["size_class"] = sizes
    test["moving_text"] = np.where(test["moving"], "moving", "still")
    lookalike = np.where(test["lookalike_share"] > 0.3, "much look-alike (>30%)", "little look-alike")
    test["lookalike_text"] = lookalike
    lines += share_table("By tremor size", "size_class", ["mild", "medium", "strong"], missed, labels, test)
    lines += share_table("By hand moving / still", "moving_text", ["moving", "still"], missed, labels, test)
    lines += share_table("By task type", "task_type", ["rest", "postural", "action"], missed, labels, test)
    lines += ["## Patterns among false alarms (no-tremor windows only)", ""]
    lines += share_table("By source", "source", ["patient, no tremor", "healthy", "synthetic only"], alarms, ~labels, test)
    lines += share_table("By look-alike movement", "lookalike_text",
                         ["much look-alike (>30%)", "little look-alike"], alarms, ~labels, test)
    lines += share_table("By hand moving / still", "moving_text", ["moving", "still"], alarms, ~labels, test)
    lines += share_table("By task type of the added segment", "task_type", ["rest", "postural", "action", "none"],
                         alarms, ~labels, test)
    pts = (~labels) & (test["source"] == "patient, no tremor")
    lines += ["Size of the added (unmarked) patient movement: false alarms median %.2f px, "
              "correctly passed median %.2f px." % (np.median(test["strength_px"][pts & pred]),
                                                    np.median(test["strength_px"][pts & ~pred])), ""]

    # ---------------- corrector
    data = np.load(DERIVED / "corrector_test.npz")
    shaky, clean = data["shaky"], data["clean"]
    gate = detector_gate(detector, shaky)[..., None]
    ours = shaky + gate * corrector_offsets(load_corrector(CORRECTOR_FILE), shaky)
    one_euro = run_filter(OneEuroFilter, shaky)
    dist = lambda out: np.linalg.norm(out[:, SKIP:] - clean[:, SKIP:], axis=2).mean(axis=1)
    d_ours, d_none, d_oe = dist(ours), dist(shaky), dist(one_euro)
    worse = d_ours - np.minimum(d_none, d_oe)
    print("Corrector: worse than both no filter and One Euro's best in %d of %d sequences" % (
        (worse > 0).sum(), len(worse)))
    lines += ["## Corrector examples", "",
              "Our system (corrector + detector gate) is further from the intended path than the "
              "better of no filter and One Euro in %d of %d test sequences (%d of %d with marked "
              "tremor)." % ((worse > 0).sum(), len(worse), ((worse > 0) & data["tremor"]).sum(),
                            data["tremor"].sum()), ""]
    for k, i in enumerate(np.argsort(-worse)[:2], start=1):
        t = np.arange(SKIP, shaky.shape[1]) / RATE
        fig, axes = plt.subplots(1, 2, figsize=(14, 4.5))
        for name, out, style in [("intended", clean, "k-"), ("raw (shaky)", shaky, "r:"),
                                 ("One Euro", one_euro, "g-"), ("our system", ours, "b-")]:
            axes[0].plot(out[i, SKIP:, 0], out[i, SKIP:, 1], style, label=name, linewidth=1)
            axes[1].plot(t, np.linalg.norm(out[i, SKIP:] - clean[i, SKIP:], axis=1), style, label=name)
        axes[0].invert_yaxis()
        axes[0].set(title="Path on screen (px)")
        axes[0].legend(fontsize=8)
        axes[1].plot(t, 30 * gate[i, SKIP:, 0], color="orange", label="detector gate (x30)")
        axes[1].set(title="Distance from the intended path (px)", xlabel="time (s)")
        axes[1].legend(fontsize=8)
        fig.suptitle("Corrector worse: %s, %s, tremor size %.1f px, marked tremor: %s" % (
            data["condition"][i], data["task_type"][i], data["strength_px"][i], bool(data["tremor"][i])), fontsize=10)
        fig.tight_layout()
        fig.savefig(OUT / ("corrector_worse_%d.png" % k), dpi=80)
        plt.close(fig)
        lines.append("- `corrector_worse_%d.png`: average distance ours %.2f px, no filter %.2f px, "
                     "One Euro %.2f px; %s, %s, tremor %.1f px, marked tremor %s, mean gate %.2f" % (
                         k, d_ours[i], d_none[i], d_oe[i], data["condition"][i], data["task_type"][i],
                         data["strength_px"][i], bool(data["tremor"][i]), gate[i, SKIP:].mean()))
    (OUT / "failure_facts.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
